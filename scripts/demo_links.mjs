// Demo share links + QR codes for the judges' table. Every link is checked against the app's data first.
// Usage: npm run demo:links -- https://<public-host>   (writes docs/DEMO_LINKS.md, docs/qr/*.svg, docs/qr/print.html)
// `t` is UTC, the same format the app writes into the URL: 2021-09-02T16 = noon ET, Ida's crest.
import fs from "node:fs";
import QRCode from "qrcode";

const ROOT = new URL("../", import.meta.url);
const read = (p) => JSON.parse(fs.readFileSync(new URL(p, ROOT), "utf8"));

export const LINKS = [
  { slug: "ida-crest-scott", title: "Ida crest, guided from Scott Hall",
    params: { scenario: "ida", t: "2021-09-02T16", from: "Scott Hall", guide: "1" },
    say: "Noon, Sept 2 2021: the record crest. Route from College Ave around the closed roads, spoken." },
  { slug: "ida-rising-brower", title: "Ida rising, guided from Brower Commons",
    params: { scenario: "ida", t: "2021-09-02T08", from: "Brower Commons", guide: "1" },
    say: "4 AM ET, 8 hours before the crest: which roads are already gone." },
  { slug: "whatif-major-livingston", title: "What-if: major flood (33 ft), from Livingston Apartments",
    params: { scenario: "whatif", stage: "33", from: "Livingston Apartments", guide: "1" },
    say: "A major flood we haven't had yet: the route from Livingston." },
  { slug: "voice", title: "Voice assistant (hands-free)",
    params: { scenario: "ida", t: "2021-09-02T16", from: "Scott Hall", voice: "1" },
    say: "Tap anywhere, then talk: \"Where should I go?\" Works with VoiceOver." },
];

/** Problems with one link's parameters, judged against the same data the app loads. */
export function check(params, { names, series }) {
  const errs = [];
  if (params.from && !names.has(params.from.toLowerCase())) errs.push(`unknown start "${params.from}"`);
  if (params.scenario === "ida" && params.t) {
    const first = series[0][0].slice(0, 13), last = series.at(-1)[0].slice(0, 13);
    if (params.t < first || params.t > last) errs.push(`t=${params.t} outside the Ida replay (${first}..${last})`);
  }
  if (params.scenario === "whatif" && !(+params.stage >= 15 && +params.stage <= 45)) errs.push(`stage ${params.stage} outside the 15-45 ft slider`);
  if (params.guide === "1" && !params.from) errs.push("guide=1 needs from=");
  return errs;
}

export const urlFor = (base, params) => `${base.replace(/\/$/, "")}/?${new URLSearchParams(params)}`;

if (import.meta.url === `file://${process.argv[1]}`) {
  const base = process.argv[2] || "http://localhost:5173";
  if (/localhost|127\.0\.0\.1/.test(base)) console.warn(`! ${base} only works on this laptop: pass the public URL before printing QR codes`);
  const starts = read("web/public/data/starts.json"), places = read("web/public/data/places.json");
  const data = {
    names: new Set([...starts, ...places.filter((p) => p.kind === "gather")].map((s) => s.name.toLowerCase())),
    series: read("web/public/data/ida.json").series,
  };

  let bad = 0;
  for (const l of LINKS) for (const e of check(l.params, data)) { console.error(`✗ ${l.slug}: ${e}`); bad++; }
  if (bad) process.exit(1);

  const qrDir = new URL("docs/qr/", ROOT);
  fs.mkdirSync(qrDir, { recursive: true });
  const rows = [], cards = [];
  for (const l of LINKS) {
    const url = urlFor(base, l.params);
    const svg = await QRCode.toString(url, { type: "svg", errorCorrectionLevel: "M", margin: 2 });
    fs.writeFileSync(new URL(`${l.slug}.svg`, qrDir), svg);
    rows.push(`### ${l.title}\n${l.say}\n\n<${url}>\n\n![QR](qr/${l.slug}.svg)\n`);
    cards.push(`<figure><div class="qr">${svg}</div><figcaption><b>${l.title}</b><br>${l.say}</figcaption></figure>`);
    console.log(`✓ ${l.slug}  ${url}`);
  }
  fs.writeFileSync(new URL("docs/DEMO_LINKS.md", ROOT),
    `# Demo links\n\nGenerated by \`npm run demo:links -- ${base}\`. Test each in a private window before the demo.\n\n${rows.join("\n")}`);
  fs.writeFileSync(new URL("print.html", qrDir), `<!doctype html><meta charset="utf-8"><title>RUAfloat · demo QR codes</title>
<style>body{font:15px system-ui;margin:24px}main{display:grid;grid-template-columns:1fr 1fr;gap:28px}figure{margin:0;break-inside:avoid}.qr svg{width:220px;height:220px}h1{font-size:22px}</style>
<h1>RUAfloat · scan to open a demo</h1><main>${cards.join("")}</main>`);
  console.log(`\nWrote docs/DEMO_LINKS.md and docs/qr/ (open docs/qr/print.html to print).`);
}
